// Gerber RS-274X (X2 attributes) + Excellon drill export from the routed PCB.
// Produces the file set PCB fabs (JLCPCB, PCBWay, OSH Park ...) accept.

const fmt = (v) => Math.round(v * 1e6).toString(); // FSLAX46Y46, mm

function gerberFile(func, polarity, body) {
  return [
    '%TF.GenerationSoftware,CircuitDesigner,1.0*%',
    `%TF.FileFunction,${func}*%`,
    `%TF.FilePolarity,${polarity}*%`,
    '%FSLAX46Y46*%',
    '%MOMM*%',
    '%LPD*%',
    ...body,
    'M02*',
    '',
  ].join('\n');
}

class Apertures {
  constructor() { this.map = new Map(); this.next = 10; }
  get(kind, a, b) {
    const key = `${kind}${a.toFixed(4)}${b !== undefined ? 'X' + b.toFixed(4) : ''}`;
    if (!this.map.has(key)) this.map.set(key, { code: this.next++, def: `%ADD${this.next - 1}${key}*%` });
    return this.map.get(key).code;
  }
  defs() { return [...this.map.values()].map((x) => x.def); }
}

function copperLayer(pcb, layer, H, mask = 0) {
  const ap = new Apertures();
  const ops = [];
  const Y = (y) => fmt(H - y);
  let cur = -1;
  const select = (code) => { if (code !== cur) { ops.push(`D${code}*`); cur = code; } };
  const L = layer === 'F' ? 0 : 1;
  const padAperture = (p) => {
    const w = p.w + 2 * mask, h = p.h + 2 * mask;
    if (p.shape === 'circle' && Math.abs(w - h) < 1e-6) return ap.get('C,', w);
    if (p.shape === 'oval' || p.shape === 'circle') return Math.abs(w - h) < 1e-6 ? ap.get('C,', w) : ap.get('O,', w, h);
    return ap.get('R,', w, h);
  };
  if (!mask) {
    ops.push('G01*');
    for (const t of pcb.tracks.filter((t) => t.layer === `${layer}.Cu`)) {
      select(ap.get('C,', t.w));
      ops.push(`X${fmt(t.x1)}Y${Y(t.y1)}D02*`, `X${fmt(t.x2)}Y${Y(t.y2)}D01*`);
    }
    for (const v of pcb.vias) { select(ap.get('C,', v.d)); ops.push(`X${fmt(v.x)}Y${Y(v.y)}D03*`); }
  }
  for (const p of pcb.pads) {
    const onLayer = p.type === 'thru' || L === 0;
    if (!onLayer) continue;
    select(padAperture(p));
    ops.push(`X${fmt(p.x)}Y${Y(p.y)}D03*`);
  }
  return [...ap.defs(), ...ops];
}

function pasteLayer(pcb, H) {
  const ap = new Apertures();
  const ops = [];
  let cur = -1;
  for (const p of pcb.pads.filter((x) => x.type === 'smd')) {
    const code = p.shape === 'circle' ? ap.get('C,', p.w) : ap.get('R,', p.w, p.h);
    if (code !== cur) { ops.push(`D${code}*`); cur = code; }
    ops.push(`X${fmt(p.x)}Y${fmt(H - p.y)}D03*`);
  }
  return [...ap.defs(), ...ops];
}

function silkLayer(pcb, H) {
  const ap = new Apertures();
  const code = ap.get('C,', 0.15);
  const ops = [`D${code}*`, 'G01*'];
  const seg = (x1, y1, x2, y2) => ops.push(`X${fmt(x1)}Y${fmt(H - y1)}D02*`, `X${fmt(x2)}Y${fmt(H - y2)}D01*`);
  for (const c of pcb.components) {
    for (const s of c.silk) {
      if (s.type === 'line') seg(s.x1, s.y1, s.x2, s.y2);
      else {
        const N = 32;
        for (let i = 0; i < N; i++) {
          const a1 = (i / N) * 2 * Math.PI, a2 = ((i + 1) / N) * 2 * Math.PI;
          seg(s.cx + s.r * Math.cos(a1), s.cy + s.r * Math.sin(a1), s.cx + s.r * Math.cos(a2), s.cy + s.r * Math.sin(a2));
        }
      }
    }
  }
  return [...ap.defs(), ...ops];
}

function edgeLayer(pcb) {
  const { width: W, height: H } = pcb.board;
  const ap = new Apertures();
  const code = ap.get('C,', 0.1);
  return [...ap.defs(), `D${code}*`, 'G01*', `X0Y0D02*`, `X${fmt(W)}Y0D01*`, `X${fmt(W)}Y${fmt(H)}D01*`, `X0Y${fmt(H)}D01*`, `X0Y0D01*`];
}

function drillFile(pcb) {
  const H = pcb.board.height;
  const holes = [...pcb.pads.filter((p) => p.type === 'thru' && p.drill).map((p) => ({ x: p.x, y: p.y, d: p.drill })), ...pcb.vias.map((v) => ({ x: v.x, y: v.y, d: v.drill }))];
  const sizes = [...new Set(holes.map((h) => h.d.toFixed(3)))].sort((a, b) => a - b);
  const L = ['M48', '; DRILL file generated by Circuit Designer', '; FORMAT={-:-/ absolute / metric / decimal}', 'FMAT,2', 'METRIC'];
  sizes.forEach((s, i) => L.push(`T${i + 1}C${s}`));
  L.push('%', 'G90', 'G05');
  sizes.forEach((s, i) => {
    L.push(`T${i + 1}`);
    for (const h of holes.filter((x) => x.d.toFixed(3) === s)) L.push(`X${h.x.toFixed(3)}Y${(H - h.y).toFixed(3)}`);
  });
  L.push('M30', '');
  return L.join('\n');
}

/** Returns { filename: content } for a complete fabrication set. */
export function exportGerbers(pcb, base = 'board') {
  const H = pcb.board.height;
  return {
    [`${base}-F_Cu.gtl`]: gerberFile('Copper,L1,Top', 'Positive', copperLayer(pcb, 'F', H)),
    [`${base}-B_Cu.gbl`]: gerberFile('Copper,L2,Bot', 'Positive', copperLayer(pcb, 'B', H)),
    [`${base}-F_Mask.gts`]: gerberFile('Soldermask,Top', 'Negative', copperLayer(pcb, 'F', H, 0.05)),
    [`${base}-B_Mask.gbs`]: gerberFile('Soldermask,Bot', 'Negative', copperLayer(pcb, 'B', H, 0.05)),
    [`${base}-F_Paste.gtp`]: gerberFile('Paste,Top', 'Positive', pasteLayer(pcb, H)),
    [`${base}-F_Silkscreen.gto`]: gerberFile('Legend,Top', 'Positive', silkLayer(pcb, H)),
    [`${base}-Edge_Cuts.gm1`]: gerberFile('Profile,NP', 'Positive', edgeLayer(pcb)),
    [`${base}.drl`]: drillFile(pcb),
  };
}
