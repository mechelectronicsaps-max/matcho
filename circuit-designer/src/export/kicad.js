// KiCad exports: .kicad_pcb (KiCad 7/8 format, opens directly in Pcbnew) and
// a KiCad netlist (.net) that can be imported into an existing board.

const q = (s) => `"${String(s).replace(/\\/g, '\\\\').replace(/"/g, '\\"')}"`;
const n = (v) => Number(v.toFixed(4)).toString();
const OX = 50, OY = 50; // place the board on the sheet

export function exportKicadPcb(design, pcb) {
  const nets = ['', ...design.nets.map((x) => x.name)];
  const netCode = new Map(nets.map((name, i) => [name, i]));
  const L = [];
  L.push('(kicad_pcb (version 20221018) (generator circuit_designer)');
  L.push('  (general (thickness 1.6))');
  L.push('  (paper "A4")');
  L.push(`  (title_block (title ${q(design.title)}) (comment 1 "Generated by Circuit Designer - review before manufacturing"))`);
  L.push('  (layers');
  for (const [i, name, type, alias] of [[0, 'F.Cu', 'signal'], [31, 'B.Cu', 'signal'], [34, 'B.Paste', 'user'], [35, 'F.Paste', 'user'], [36, 'B.SilkS', 'user', 'B.Silkscreen'], [37, 'F.SilkS', 'user', 'F.Silkscreen'], [38, 'B.Mask', 'user'], [39, 'F.Mask', 'user'], [40, 'Dwgs.User', 'user', 'User.Drawings'], [44, 'Edge.Cuts', 'user'], [46, 'B.CrtYd', 'user', 'B.Courtyard'], [47, 'F.CrtYd', 'user', 'F.Courtyard'], [48, 'B.Fab', 'user'], [49, 'F.Fab', 'user']]) {
    L.push(`    (${i} ${q(name)} ${type}${alias ? ` ${q(alias)}` : ''})`);
  }
  L.push('  )');
  L.push(`  (setup (pad_to_mask_clearance 0.05) (pcbplotparams (layerselection 0x00010fc_ffffffff) (outputdirectory "gerbers/")))`);
  for (const [name, code] of netCode) L.push(`  (net ${code} ${q(name)})`);

  const byRef = new Map(design.components.map((c) => [c.ref, c]));
  for (const pc of pcb.components) {
    const c = byRef.get(pc.ref);
    const fp = c.fp;
    L.push(`  (footprint ${q(`CircuitDesigner:${fp.name}`)} (layer "F.Cu") (at ${n(pc.x + OX)} ${n(pc.y + OY)}${pc.rot ? ` ${pc.rot}` : ''})`);
    L.push(`    (descr ${q(fp.description ?? '')})`);
    L.push(`    (fp_text reference ${q(c.ref)} (at 0 ${n(fp.bbox.minY - 0.8)}${pc.rot ? ` ${pc.rot}` : ''}) (layer "F.SilkS") (effects (font (size 1 1) (thickness 0.15))))`);
    L.push(`    (fp_text value ${q(c.value)} (at 0 ${n(fp.bbox.maxY + 0.8)}${pc.rot ? ` ${pc.rot}` : ''}) (layer "F.Fab") (effects (font (size 1 1) (thickness 0.15))))`);
    for (const s of fp.silk) {
      if (s.type === 'line') L.push(`    (fp_line (start ${n(s.x1)} ${n(s.y1)}) (end ${n(s.x2)} ${n(s.y2)}) (stroke (width 0.12) (type solid)) (layer "F.SilkS"))`);
      else L.push(`    (fp_circle (center ${n(s.cx)} ${n(s.cy)}) (end ${n(s.cx + s.r)} ${n(s.cy)}) (stroke (width 0.12) (type solid)) (fill none) (layer "F.SilkS"))`);
    }
    const b = fp.bbox;
    L.push(`    (fp_rect (start ${n(b.minX)} ${n(b.minY)}) (end ${n(b.maxX)} ${n(b.maxY)}) (stroke (width 0.05) (type solid)) (fill none) (layer "F.CrtYd"))`);
    for (const p of fp.pads) {
      const net = design.pinNet[`${c.ref}.${p.num}`];
      const netStr = net ? ` (net ${netCode.get(net)} ${q(net)})` : '';
      const ang = pc.rot ? ` ${pc.rot}` : '';
      if (p.type === 'thru') {
        const shape = p.shape === 'rect' ? 'rect' : p.w === p.h && p.shape !== 'oval' ? 'circle' : 'oval';
        L.push(`    (pad ${q(p.num)} thru_hole ${shape} (at ${n(p.x)} ${n(p.y)}${ang}) (size ${n(p.w)} ${n(p.h)}) (drill ${n(p.drill)}) (layers "*.Cu" "*.Mask")${netStr})`);
      } else {
        const shape = p.shape === 'roundrect' ? 'roundrect' : p.shape === 'circle' ? 'circle' : 'rect';
        L.push(`    (pad ${q(p.num)} smd ${shape} (at ${n(p.x)} ${n(p.y)}${ang}) (size ${n(p.w)} ${n(p.h)}) (layers "F.Cu" "F.Paste" "F.Mask")${shape === 'roundrect' ? ' (roundrect_rratio 0.25)' : ''}${netStr})`);
      }
    }
    L.push('  )');
  }
  const { width, height } = pcb.board;
  L.push(`  (gr_rect (start ${OX} ${OY}) (end ${n(OX + width)} ${n(OY + height)}) (stroke (width 0.1) (type default)) (fill none) (layer "Edge.Cuts"))`);
  L.push(`  (gr_text ${q(design.title)} (at ${n(OX + width / 2)} ${n(OY + height + 2.5)}) (layer "Dwgs.User") (effects (font (size 1.2 1.2) (thickness 0.15))))`);
  for (const t of pcb.tracks) L.push(`  (segment (start ${n(t.x1 + OX)} ${n(t.y1 + OY)}) (end ${n(t.x2 + OX)} ${n(t.y2 + OY)}) (width ${n(t.w)}) (layer ${q(t.layer)}) (net ${netCode.get(t.net)}))`);
  for (const v of pcb.vias) L.push(`  (via (at ${n(v.x + OX)} ${n(v.y + OY)}) (size ${n(v.d)}) (drill ${n(v.drill)}) (layers "F.Cu" "B.Cu") (net ${netCode.get(v.net)}))`);
  L.push(')');
  return L.join('\n') + '\n';
}

export function exportKicadNetlist(design) {
  const L = [];
  L.push('(export (version "E")');
  L.push(`  (design (source ${q(design.title)}) (tool "circuit-designer"))`);
  L.push('  (components');
  for (const c of design.components) {
    L.push(`    (comp (ref ${q(c.ref)}) (value ${q(c.value)}) (footprint ${q(`CircuitDesigner:${c.footprint}`)}) (description ${q(c.comp.description)}) (libsource (lib "circuit-designer") (part ${q(c.part)}) (description ${q(c.comp.name)})))`);
  }
  L.push('  )');
  L.push('  (nets');
  design.nets.forEach((net, i) => {
    L.push(`    (net (code ${q(i + 1)}) (name ${q(net.name)})`);
    for (const nd of net.nodes) {
      const c = design.components.find((x) => x.ref === nd.ref);
      const pin = c.comp.pins.find((p) => p.num === nd.pin);
      L.push(`      (node (ref ${q(nd.ref)}) (pin ${q(nd.pin)}) (pinfunction ${q(pin?.name ?? '')}))`);
    }
    L.push('    )');
  });
  L.push('  )');
  L.push(')');
  return L.join('\n') + '\n';
}

/** KiCad footprint (.kicad_mod) for one library footprint. */
export function exportKicadMod(fp) {
  const L = [`(footprint ${q(fp.name)} (version 20221018) (generator circuit_designer) (layer "F.Cu")`, `  (descr ${q(fp.description ?? '')})`];
  L.push(`  (fp_text reference "REF**" (at 0 ${n(fp.bbox.minY - 0.8)}) (layer "F.SilkS") (effects (font (size 1 1) (thickness 0.15))))`);
  L.push(`  (fp_text value ${q(fp.name)} (at 0 ${n(fp.bbox.maxY + 0.8)}) (layer "F.Fab") (effects (font (size 1 1) (thickness 0.15))))`);
  for (const s of fp.silk) {
    if (s.type === 'line') L.push(`  (fp_line (start ${n(s.x1)} ${n(s.y1)}) (end ${n(s.x2)} ${n(s.y2)}) (stroke (width 0.12) (type solid)) (layer "F.SilkS"))`);
    else L.push(`  (fp_circle (center ${n(s.cx)} ${n(s.cy)}) (end ${n(s.cx + s.r)} ${n(s.cy)}) (stroke (width 0.12) (type solid)) (fill none) (layer "F.SilkS"))`);
  }
  for (const p of fp.pads) {
    if (p.type === 'thru') L.push(`  (pad ${q(p.num)} thru_hole ${p.shape === 'rect' ? 'rect' : p.w === p.h ? 'circle' : 'oval'} (at ${n(p.x)} ${n(p.y)}) (size ${n(p.w)} ${n(p.h)}) (drill ${n(p.drill)}) (layers "*.Cu" "*.Mask"))`);
    else L.push(`  (pad ${q(p.num)} smd ${p.shape === 'circle' ? 'circle' : p.shape === 'roundrect' ? 'roundrect' : 'rect'} (at ${n(p.x)} ${n(p.y)}) (size ${n(p.w)} ${n(p.h)}) (layers "F.Cu" "F.Paste" "F.Mask")${p.shape === 'roundrect' ? ' (roundrect_rratio 0.25)' : ''})`);
  }
  L.push(')');
  return L.join('\n') + '\n';
}
